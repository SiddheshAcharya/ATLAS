"""Generate web/src/theme-light.generated.css from Tailwind's own default palette.

The app's classes are written dark-first (bg-ink-950, text-accent-300, ...). Tailwind v4 compiles
every colour utility to a CSS variable (--color-red-300 ...), so a light theme for the semantic
palettes is just those variables mirrored: 50<->950, 100<->900, 200<->800, 300<->700, 400<->600.
The neutral `ink` and `accent` palettes are ATLAS's own and are hand-tuned for both themes in
src/index.css, so they are not generated here.
Re-run after upgrading Tailwind or using a new palette:  python web/scripts/gen_light_theme.py
"""

import re
from pathlib import Path

WEB = Path(__file__).resolve().parent.parent
PALETTES = ["red", "emerald", "amber", "yellow", "violet", "fuchsia"]
SHADES = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"]

theme = (WEB / "node_modules" / "tailwindcss" / "theme.css").read_text(encoding="utf-8")
value = {
    (p, s): re.search(rf"--color-{p}-{s}:\s*([^;]+);", theme).group(1).strip()  # type: ignore[union-attr]
    for p in PALETTES
    for s in SHADES
}
lines = [
    f"  --color-{p}-{s}: {value[(p, mirrored)]};"
    for p in PALETTES
    for s, mirrored in zip(SHADES, reversed(SHADES), strict=True)
]
(WEB / "src" / "theme-light.generated.css").write_text(
    "/* GENERATED by web/scripts/gen_light_theme.py — do not edit by hand.\n"
    "   Light theme = the semantic palettes the app uses, mirrored (50<->950, 100<->900, ...), so the\n"
    "   dark-first utility classes (bg-red-500/10, text-emerald-300, ...) render as a light theme. */\n"
    ':root[data-theme="light"] {\n' + "\n".join(lines) + "\n}\n",
    encoding="utf-8",
)
print(f"wrote {len(lines)} variables")
