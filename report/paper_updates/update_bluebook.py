def all_pars():
    return list(doc.element.body.iter(W + "p"))


def par(anchor: str, nth: int | None = None):
    hits = [p for p in all_pars() if anchor in text_of(p)]
    if nth is not None:
        return hits[nth]
    assert len(hits) == 1, f"{len(hits)} paragraphs contain {anchor!r}"
    return hits[0]


def rewrite(anchor: str, new: str, why: str = "", nth: int | None = None):
    p = par(anchor, nth)
    old = text_of(p)
    set_par_text(p, new)
    log.append(f"### {why or 'Paragraph'}\n**Old:** {old}\n\n**New:** {new}\n")
    return p


def sub(anchor: str, old_part: str, new_part: str, why: str = "", nth: int | None = None):
    p = par(anchor, nth)
    old = text_of(p)
    assert old_part in old, f"{old_part!r} not in paragraph {anchor!r}"
    if not replace_in_runs(p, old_part, new_part):
        set_par_text(p, old.replace(old_part, new_part, 1))
    log.append(f"### {why or 'Sentence'}\n**Old:** …{old_part}…\n\n**New:** …{new_part}…\n")


def replace_placeholder(anchor: str, new: str, why: str, template):
    """Put `new` in a paragraph styled like `template`, in place of an italic '[ Reserved … ]' line."""
    ph = par(anchor)
    old = text_of(ph)
    q = insert_par_after(ph, template, new)
    ph.getparent().remove(ph)
    log.append(f"### {why}\n**Old:** {old}\n\n**New:** {new}\n")
    return q


def add_after(p, new: str, why: str, template=None):
    q = insert_par_after(p, template if template is not None else p, new)
    log.append(f"### {why}\n**New:** {new}\n")
    return q


def table(header_part: str):
    hits = [t for t in doc.element.body.iter(W + "tbl") if header_part in "|".join(cell_texts(t)[0])]
    assert len(hits) == 1, f"{len(hits)} tables with header {header_part!r}"
    return hits[0]


def cell(tbl, r, c, new, why=""):
    old = cell_texts(tbl)[r][c]
    set_cell(tbl, r, c, new)
    log.append(f"### {why or 'Table cell'} (row {r}, col {c})\n**Old:** {old}\n\n**New:** {new}\n")


def image_pars():
    return [p for p in body(doc) if p.tag == W + "p" and image_info(doc, p)]


def figure(n: int, png: Path, why: str, width_in: float | None = None):
    replace_image(doc, image_pars()[n], str(png), width_in)
    log.append(f"### {why}\nImage replaced with `{png.name}`.\n")


