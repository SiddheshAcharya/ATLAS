from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
from docx_tools import (  # noqa: E402
    W, Document, body, cell_texts, image_info, insert_par_after, replace_image, set_cell,
    insert_head_body_after, replace_in_runs, set_head_body, set_par_text, text_of, text_runs,
)

SRC = HERE / "ATLAS_FINAL_original_copy.docx"
OUT = HERE / "ATLAS_FINAL_updated.docx"
LOG = HERE / "CHANGES_paper.md"
FIG = HERE / "fig"

doc = Document(str(SRC))
log: list[str] = []


def all_pars():
    return list(doc.element.body.iter(W + "p"))


def par(anchor: str):
    hits = [p for p in all_pars() if anchor in text_of(p)]
    assert len(hits) == 1, f"{len(hits)} paragraphs contain {anchor!r}"
    return hits[0]


def rewrite(anchor: str, new: str, why: str = "") -> None:
    p = par(anchor)
    old = text_of(p)
    import re as _re
    m = _re.match(r"(Fig\. \d+\.)(.*)", new, _re.S)
    if m:  # captions: keep the bold 'Fig. N.' run, normal body
        set_head_body(p, m.group(1), m.group(2))
    else:
        set_par_text(p, new)
    log.append(f"### {why or 'Paragraph'}\n**Old:** {old}\n\n**New:** {new}\n")


def sub(anchor: str, old_part: str, new_part: str, why: str = "") -> None:
    p = par(anchor)
    old = text_of(p)
    assert old_part in old, f"{old_part!r} not in paragraph {anchor!r}"
    if not replace_in_runs(p, old_part, new_part):
        set_par_text(p, old.replace(old_part, new_part, 1))
    log.append(f"### {why or 'Sentence'}\n**Old:** …{old_part}…\n\n**New:** …{new_part}…\n")


def add_after(anchor: str, new: str, why: str = "") -> None:
    p = par(anchor)
    insert_par_after(p, p, new)
    log.append(f"### {why or 'Added paragraph'}\n**New:** {new}\n")


def table(header_part: str):
    hits = [t for t in doc.element.body.iter(W + "tbl")
            if header_part in "|".join(cell_texts(t)[0])]
    assert len(hits) == 1, f"{len(hits)} tables with header {header_part!r}"
    return hits[0]


def cell(tbl, r, c, new, why=""):
    old = cell_texts(tbl)[r][c]
    set_cell(tbl, r, c, new)
    log.append(f"### {why or 'Table cell'} (row {r}, col {c})\n**Old:** {old}\n\n**New:** {new}\n")


def figure(n_th_image: int, png: str, why: str) -> None:
    imgs = [p for p in body(doc) if p.tag == W + "p" and image_info(doc, p)]
    replace_image(doc, imgs[n_th_image], str(FIG / png))
    log.append(f"### {why}\nImage replaced with `fig/{png}` (redrawn to the system as built).\n")


